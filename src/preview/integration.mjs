// @ts-check
/**
 * Everything that differs between the two build modes, in one place.
 *
 * Production (static):  writes dist/_headers with the strict security headers (framing DENIED).
 * Preview (server):     adds the draft-mode routes and a middleware, and writes dist/_headers that
 *                       allows the Studio to frame the site.
 *
 * Why not just netlify.toml [[headers]]? Two Netlify limitations (docs: "Custom headers"):
 *   1. File-based headers can't be scoped to a deploy context, so production and preview
 *      can't get different X-Frame-Options from the same netlify.toml.
 *   2. They are not applied to responses from functions (= every server-rendered preview page).
 * So: each build writes its own _headers file (for static files), and the preview build sets the
 * same headers from middleware (for server-rendered pages).
 */
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { COMMON_HEADERS, framingHeaders } from './headers.mjs';

/** @param {boolean} visualEditing @param {string} studioOrigin */
function headersFile(visualEditing, studioOrigin) {
  const lines = (/** @type {Record<string, string>} */ headers) => Object.entries(headers).map(([name, value]) => `  ${name}: ${value}`);
  return [
    '# Generated by src/preview/integration.mjs at build time. Do not edit.',
    '/_astro/*',
    '  Cache-Control: public, max-age=31536000, immutable',
    '/fonts/*',
    '  Cache-Control: public, max-age=31536000, immutable',
    '  Access-Control-Allow-Origin: *',
    '/*',
    ...lines(COMMON_HEADERS),
    ...lines(framingHeaders(visualEditing, studioOrigin)),
    '',
  ].join('\n');
}

/**
 * @param {{ visualEditing: boolean, studioUrl: string }} options
 * @returns {import('astro').AstroIntegration}
 */
export default function previewMode({ visualEditing, studioUrl }) {
  const studioOrigin = new URL(studioUrl).origin;

  return {
    name: 'everline-preview-mode',
    hooks: {
      'astro:config:setup': ({ injectRoute, addMiddleware, updateConfig }) => {
        if (visualEditing) {
          // These routes only exist in the preview build. In the static build they would be
          // pre-rendered at build time (and fail), so they live outside src/pages on purpose.
          injectRoute({
            pattern: '/api/draft-mode/enable',
            entrypoint: fileURLToPath(new URL('./routes/enable.ts', import.meta.url)),
            prerender: false,
          });
          injectRoute({
            pattern: '/api/draft-mode/disable',
            entrypoint: fileURLToPath(new URL('./routes/disable.ts', import.meta.url)),
            prerender: false,
          });
          addMiddleware({ entrypoint: fileURLToPath(new URL('./middleware.ts', import.meta.url)), order: 'post' });
        }

        // `@preview/visual-editing` points at the real Visual Editing component only in the
        // preview build. In production it points at an empty component, so React and the
        // overlay code are never even imported: nothing to tree-shake, nothing to ship.
        const component = visualEditing ? './VisualEditing.astro' : './NoVisualEditing.astro';
        updateConfig({
          vite: {
            resolve: { alias: { '@preview/visual-editing': fileURLToPath(new URL(component, import.meta.url)) } },
          },
        });
      },

      'astro:build:done': async ({ dir }) => {
        await writeFile(new URL('_headers', dir), headersFile(visualEditing, studioOrigin));
      },
    },
  };
}
