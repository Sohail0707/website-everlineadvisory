// @ts-check
/**
 * Everything that differs between the two build modes, in one place.
 *
 * Server mode (SANITY_VISUAL_EDITING=true, what Netlify runs):
 *   adds the draft-mode and revalidate routes and the caching/security middleware,
 *   and points `@preview/visual-editing` at the real Visual Editing component.
 * Static mode (false, e.g. a host without functions):
 *   none of the above; `@preview/visual-editing` is an empty component.
 * Both: write dist/_headers for the files Netlify serves directly (fonts, /_astro/, 404, thanks).
 *
 * Why not netlify.toml [[headers]]? Netlify doesn't apply file-based headers to responses from
 * functions (= every server-rendered page), and they can't differ per deploy context.
 * So static files get dist/_headers, and server-rendered pages get the same headers from
 * middleware.ts (which also decides about caching and framing per request).
 */
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { COMMON_HEADERS, framingHeaders } from './headers.mjs';

const here = (/** @type {string} */ path) => fileURLToPath(new URL(path, import.meta.url));

/** @param {string} studioOrigin */
function headersFile(studioOrigin) {
  const lines = (/** @type {Record<string, string>} */ headers) =>
    Object.entries(headers).map(([name, value]) => `  ${name}: ${value}`);
  return [
    '# Generated by src/preview/integration.mjs at build time. Do not edit.',
    '/_astro/*',
    '  Cache-Control: public, max-age=31536000, immutable',
    '/fonts/*',
    '  Cache-Control: public, max-age=31536000, immutable',
    '  Access-Control-Allow-Origin: *',
    '/*',
    ...lines(COMMON_HEADERS),
    ...lines(framingHeaders(studioOrigin)),
    '',
  ].join('\n');
}

/**
 * @param {{ visualEditing: boolean, studioUrl: string }} options
 * @returns {import('astro').AstroIntegration}
 */
export default function previewMode({ visualEditing, studioUrl }) {
  const studioOrigin = new URL(studioUrl).origin;
  return {
    name: 'everline-preview-mode',
    hooks: {
      'astro:config:setup': ({ injectRoute, addMiddleware, updateConfig }) => {
        if (visualEditing) {
          // These routes only exist in server mode. In a static build they would be
          // pre-rendered at build time (and fail), so they live outside src/pages on purpose.
          injectRoute({ pattern: '/api/draft-mode/enable', entrypoint: here('./routes/enable.ts'), prerender: false });
          injectRoute({ pattern: '/api/draft-mode/disable', entrypoint: here('./routes/disable.ts'), prerender: false });
          injectRoute({ pattern: '/api/revalidate', entrypoint: here('./routes/revalidate.ts'), prerender: false });
          addMiddleware({ entrypoint: here('./middleware.ts'), order: 'post' });
        }

        // `@preview/visual-editing` points at the real Visual Editing component only in server mode.
        // In static mode it is an empty component, so React and the overlay code are never imported.
        // (In server mode, React is still only sent to the browser when draft mode is on.)
        const component = visualEditing ? './VisualEditing.astro' : './NoVisualEditing.astro';
        updateConfig({
          vite: {
            resolve: { alias: { '@preview/visual-editing': here(component) } },
            // Dev server only: pre-bundle the overlay so Vite converts its CommonJS dependencies
            // (lodash, used by @sanity/mutate). Without this, `astro dev` fails to start the overlay with
            // "lodash/isObject.js does not provide an export named 'default'". Builds aren't affected.
            ...(visualEditing ? { optimizeDeps: { include: ['@sanity/visual-editing/react', '@sanity/mutate'] } } : {}),
          },
        });
      },

      'astro:build:done': async ({ dir }) => {
        await writeFile(new URL('_headers', dir), headersFile(studioOrigin));
      },
    },
  };
}
